"""
Phase 11.2 MCP handler result wrapper.

Tools that use the LLM return a ``HandlerResult`` instead of a bare output
model instance so the executor can extract ``ExplainabilityMeta`` without
requiring the output model to carry internal bookkeeping fields.

Usage in a tool handler::

    return HandlerResult(
        output=SummariserOutput(summary="...", ...),
        llm_used=True,
        llm_fallback_used=False,
        model_used="mistral:latest",
        deterministic_fallback=False,
        confidence_note="Summary generated by language model.",
    )

If a handler returns a plain ``BaseModel`` instance (not a ``HandlerResult``),
the executor treats it as if ``llm_used=False`` and ``deterministic_fallback=True``
for backward compatibility.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from pydantic import BaseModel


@dataclass
class HandlerResult:
    """
    Wrapper returned by tool handlers to carry output + explainability metadata.

    The executor strips the metadata before building the public envelope.
    """

    output: BaseModel
    llm_used: bool = False
    llm_fallback_used: bool = False
    model_used: str = ""
    deterministic_fallback: bool = False
    confidence_note: str = ""
